"""Convert the game's Spark Wisp PNGs (copied from the main repo) into ARGB8888 arrays for the CoreS3.
Run: python3 tools/make_sprites.py  -> firmware/src/wisp_sprites.h"""
from PIL import Image
import os
MOODS = ["neutral", "happy", "laugh", "excited", "silly", "shy", "curious", "drowsy", "yawn", "sleepy",
         "b_neutral", "b_happy", "b_shy", "b_curious", "kind", "look_l", "look_r", "look_u"]
MAX_W, MAX_H = 200, 190
here = os.path.dirname(os.path.abspath(__file__))
art = os.path.join(here, "..", "art")
ims = {m: Image.open(os.path.join(art, f"spark_{m}.png")).convert("RGBA") for m in MOODS}
box = None
for im in ims.values():
    b = im.getbbox()
    box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
w0, h0 = box[2] - box[0], box[3] - box[1]
s = min(MAX_W / w0, MAX_H / h0)
W, H = round(w0 * s), round(h0 * s)
out = [f"// generated by tools/make_sprites.py from the game art (art/spark_*.png)\n#pragma once\n#include <stdint.h>\n",
       f"#define WISP_W {W}\n#define WISP_H {H}\n"]
for m in MOODS:
    im = ims[m].crop(box).resize((W, H), Image.LANCZOS)
    px = []
    for r, g, b, a in im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata():
        if a < 8: r = g = b = a = 0
        px.append(f"0x{a:02X}{r:02X}{g:02X}{b:02X}")
    out.append(f"static const uint32_t WISP_{m.upper()}[{W*H}] = {{\n" +
               ",\n".join(",".join(px[i:i+16]) for i in range(0, len(px), 16)) + "};\n")
# small versions for game screens
SMALL = ["neutral", "happy", "excited", "curious", "look_u", "b_neutral"]
s2 = min(100 / w0, 96 / h0)
W2, H2 = round(w0 * s2), round(h0 * s2)
out.append(f"#define WISPS_W {W2}\n#define WISPS_H {H2}\n")
for m in SMALL:
    im = ims[m].crop(box).resize((W2, H2), Image.LANCZOS)
    px = []
    data = im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()
    for r, g, b, a in data:
        if a < 8: r = g = b = a = 0
        px.append(f"0x{a:02X}{r:02X}{g:02X}{b:02X}")
    out.append(f"static const uint32_t WISPS_{m.upper()}[{W2*H2}] = {{\n" +
               ",\n".join(",".join(px[i:i+16]) for i in range(0, len(px), 16)) + "};\n")
open(os.path.join(here, "..", "firmware", "src", "wisp_sprites.h"), "w").write("\n".join(out))
print(f"{len(MOODS)} moods at {W}x{H}, {len(SMALL)} small at {W2}x{H2}")
